/**
 * Builds src/lib/japaneseLessonContent.ts with study content for all SmartJP lessons.
 * Run: node scripts/build-jp-content.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { registerN5 } from "./jp-content-n5.mjs";
import { registerAdvanced } from "./jp-content-n4-n3.mjs";
import { registerUpper } from "./jp-content-n2-n1.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const lessons = JSON.parse(
  fs.readFileSync(path.join(root, "tmp-jp-lessons.json"), "utf8")
);

const v = (ja, reading, meaningZh, romaji) => ({
  ja,
  reading,
  meaningZh,
  ...(romaji ? { romaji } : {}),
});
const e = (ja, reading, meaningZh) => ({ ja, reading, meaningZh });

/** @type {Record<string, {vocab:any[], examples:any[], tipsZh:string[], practiceZh:string[]}>} */
const CONTENT = {};

function set(id, vocab, examples, tipsZh, practiceZh) {
  CONTENT[id] = { vocab, examples, tipsZh, practiceZh };
}

const begPath = path.join(root, "tmp-content-beg.json");
if (fs.existsSync(begPath)) {
  Object.assign(CONTENT, JSON.parse(fs.readFileSync(begPath, "utf8")));
}

registerN5(set, v, e);
registerAdvanced(set, v, e);
registerUpper(set, v, e);

const missing = lessons.map((l) => l.id).filter((id) => !CONTENT[id]);
if (missing.length) {
  console.error("Missing content for:", missing.join(", "));
  process.exit(1);
}

function esc(str) {
  return String(str).replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

function dumpVocab(item) {
  const parts = [
    `ja: ${JSON.stringify(item.ja)}`,
    `reading: ${JSON.stringify(item.reading)}`,
    `meaningZh: ${JSON.stringify(item.meaningZh)}`,
  ];
  if (item.romaji) parts.push(`romaji: ${JSON.stringify(item.romaji)}`);
  return `{ ${parts.join(", ")} }`;
}

function dumpExample(item) {
  return `{ ja: ${JSON.stringify(item.ja)}, reading: ${JSON.stringify(item.reading)}, meaningZh: ${JSON.stringify(item.meaningZh)} }`;
}

function dumpContent(c) {
  const vocab = c.vocab.map(dumpVocab).join(",\n      ");
  const examples = c.examples.map(dumpExample).join(",\n      ");
  const tips = c.tipsZh.map((t) => JSON.stringify(t)).join(",\n      ");
  const practice = c.practiceZh.map((t) => JSON.stringify(t)).join(",\n      ");
  return `{
    vocab: [
      ${vocab}
    ],
    examples: [
      ${examples}
    ],
    tipsZh: [
      ${tips}
    ],
    practiceZh: [
      ${practice}
    ],
  }`;
}

const entries = lessons
  .map((l) => `  ${JSON.stringify(l.id)}: ${dumpContent(CONTENT[l.id])}`)
  .join(",\n");

const out = `/**
 * SmartJP — 每課完整學習內容（詞彙・讀法・例句・解說・練習）
 * Generated by scripts/build-jp-content.mjs — edit source scripts to regenerate.
 */

import type { LessonStudyContent } from "@/lib/japaneseCourse";

export const LESSON_STUDY_CONTENT: Record<string, LessonStudyContent> = {
${entries}
};

export function getLessonStudyContent(lessonId: string): LessonStudyContent | null {
  return LESSON_STUDY_CONTENT[lessonId] ?? null;
}

export function assertAllLessonsHaveContent(lessonIds: string[]): string[] {
  return lessonIds.filter((id) => !LESSON_STUDY_CONTENT[id]);
}
`;

const outPath = path.join(root, "src/lib/japaneseLessonContent.ts");
fs.writeFileSync(outPath, out, "utf8");
console.log("Wrote", outPath, "lessons:", Object.keys(CONTENT).length);

function serializePack(p) {
  const dumpV = (item) => {
    const parts = [
      `v(${JSON.stringify(item.ja)}, ${JSON.stringify(item.reading)}, ${JSON.stringify(item.meaningZh)}`,
    ];
    if (item.romaji) parts[0] += `, ${JSON.stringify(item.romaji)}`;
    parts[0] += ")";
    return parts[0];
  };
  const dumpE = (item) =>
    `e(${JSON.stringify(item.ja)}, ${JSON.stringify(item.reading)}, ${JSON.stringify(item.meaningZh)})`;
  const dumpArr = (arr, fn) => arr.map(fn).join(",\n      ");
  const culture =
    p.cultureTipsZh?.length
      ? `,\n    [\n      ${p.cultureTipsZh.map((t) => JSON.stringify(t)).join(",\n      ")}\n    ]`
      : "";
  return `pack(
    [
      ${dumpArr(p.vocab, dumpV)}
    ],
    [
      ${dumpArr(p.examples, dumpE)}
    ],
    [
      ${p.tipsZh.map((t) => JSON.stringify(t)).join(",\n      ")}
    ],
    [
      ${p.practiceZh.map((t) => JSON.stringify(t)).join(",\n      ")}
    ]${culture}
  )`;
}

for (const [level, prefix] of Object.entries(LEVELS)) {
  const ids = Object.keys(ALL).filter((id) => id.startsWith(`${prefix}-`)).sort();
  const entries = ids
    .map((id) => `  ${JSON.stringify(id)}: ${serializePack(ALL[id])}`)
    .join(",\n");
  const out = `import { v, e, pack } from "./helpers.mjs";

export const ${level}_PACKS = {
${entries}
};
`;
  fs.writeFileSync(path.join(__dirname, `packs-${prefix}.mjs`), out, "utf8");
  console.log(`Wrote packs-${prefix}.mjs (${ids.length} lessons)`);
}
